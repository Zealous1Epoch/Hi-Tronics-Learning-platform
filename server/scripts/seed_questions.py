def insert_questions(db, questions_data, category_id, question_type, difficulty="medium"):
    """插入一组试题"""
    inserted = 0
    for item in questions_data:
        if question_type == "single_choice":
            stem, options, answer, _ = item
            answer_json = {"answer": answer}
            keywords = None
        elif question_type == "multi_choice":
            stem, options, answer, _ = item
            answer_json = answer
            keywords = None
        elif question_type == "true_false":
            stem, answer_bool = item
            options = None
            answer_json = {"answer": answer_bool}
            keywords = None
        elif question_type == "fill_blank":
            stem, answer_text = item
            options = None
            answer_json = {"answer": answer_text}
            keywords = None
        elif question_type == "essay":
            stem, kw_list = item
            options = None
            answer_json = {"answer": stem}
            keywords = kw_list
        else:
            raise ValueError(f"Unknown type: {question_type}")

        qid = str(uuid.uuid4())
        db.execute(
            text("""
                INSERT INTO questions (id, type, stem, options, answer, keywords, difficulty, tags, section, category_id, created_by)
                VALUES (:id, :type, :stem, :options, :answer, :keywords, :difficulty, :tags, :section, :category_id, :created_by)
            """),
            {
                "id": qid,
                "type": question_type,
                "stem": stem,
                "options": json.dumps(options) if options else None,
                "answer": json.dumps(answer_json),
                "keywords": json.dumps(keywords) if keywords else None,
                "difficulty": difficulty,
                "tags": json.dumps(["管理"]),
                "section": "管理",
                "category_id": category_id,
                "created_by": ADMIN_ID,
            }
        )
        inserted += 1
    return inserted


